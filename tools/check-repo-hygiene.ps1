<#
.SYNOPSIS
  Privacy and repository hygiene gate (PRIVACY-CHECKLIST.md). Fails when tracked or staged files include
  real-data formats, secrets, keys, databases, backups, archives or national-ID-like numbers in fixtures.
#>
$ErrorActionPreference = "Stop"
Set-Location (Resolve-Path (Join-Path $PSScriptRoot ".."))
$problems = New-Object System.Collections.Generic.List[string]

$files = @(git ls-files --cached --others --exclude-standard)
$forbiddenExt = '\.(db|db-wal|db-shm|db-journal|sqlite|sqlite3|pnbk|bak|rar|zip|7z|doc|docx|xls|xlsx|ppt|pptx|pfx|p12|snk|pem|key|cer|env)$'
foreach ($f in $files) {
    if ($f -match $forbiddenExt) { $problems.Add("forbidden file type: $f") }
    if ($f -match '(^|/)(secrets|scratch-keys)/') { $problems.Add("secret directory: $f") }
}

$textExt = '\.(cs|xaml|sql|ps1|py|md|xml|json|props|targets|csproj|cmd|txt)$'
foreach ($f in $files | Where-Object { $_ -match $textExt -and (Test-Path $_) }) {
    $text = [System.IO.File]::ReadAllText((Resolve-Path $f))
    if ($text -match '-----BEGIN [A-Z ]*PRIVATE KEY-----') { $problems.Add("private key material: $f") }
    if ($text -match '(?i)(password|passwd|pwd)\s*=\s*"[^"]{6,}"' -and $f -notmatch '^tests/|^tools/|^docs/') { $problems.Add("hard-coded password-like literal: $f") }
    if ($f -match '^(tests|tools)/') {
        # 10-digit national-ID-like numbers in test/tool sources must be generated by the synthetic fixture helper.
        foreach ($m in [regex]::Matches($text, "(?<![0-9A-Fa-f])[0-9]{10}(?![0-9A-Fa-f])")) {
            $v = $m.Value
            if ($v -match '^0{6}' -or $v -eq '0012345678') { continue } # documented synthetic patterns
            if (@('2166136261', '1000000000') -contains $v) { continue } # FNV-1a offset basis; fixture modulus (not IDs)
            $problems.Add("national-ID-like number in $f : $v (use Fixtures.InvalidCheckDigitNationalId)")
        }
    }
}
foreach ($p in @("Downloads", "Telegram Desktop")) {
    $hits = @(git grep -l -i --cached "$p" -- ':!tools/check-repo-hygiene.ps1' 2>$null)
    foreach ($h in $hits) { if ($h -notmatch '^docs/') { $problems.Add("reference to a personal folder ($p): $h") } }
}

if ($problems.Count -gt 0) {
    $problems | ForEach-Object { Write-Host "HYGIENE FAIL: $_" }
    Write-Host "HYGIENE_PROBLEMS=$($problems.Count)"
    exit 1
}
Write-Host "HYGIENE_OK files_checked=$($files.Count)"
exit 0
